// Generates files that must be committed because the Worker build runs only `wrangler deploy`:
//  - src/generated/prompts.js  from prompts/*.txt  (so Workers can import the prompts)
//  - src/generated/kb.js       from kb/*.md and kb/rules.json  (essay-type knowledge base; validates kb/data)
//  - public/vendor/*           browser libraries copied from node_modules
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, readdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { ESSAY_TYPES } from '../src/essayTypes.js';
import { loadRegistry, validateRegistry } from './kb-data.mjs';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const require = createRequire(import.meta.url);

const prompts = {};
for (const file of readdirSync(path.join(root, 'prompts')).filter((f) => f.endsWith('.txt')).sort()) {
  prompts[file.replace(/\.txt$/, '')] = readFileSync(path.join(root, 'prompts', file), 'utf8').trim();
}
mkdirSync(path.join(root, 'src/generated'), { recursive: true });
writeFileSync(
  path.join(root, 'src/generated/prompts.js'),
  `// Generated by scripts/build.mjs from prompts/*.txt. Do not edit; run \`npm run build\`.\nexport const PROMPTS = ${JSON.stringify(prompts, null, 2)};\n`,
);

// ---- knowledge base: one guidance file per essay type, plus requirement notes (kb/rules.json).
// The source register (kb/data) is validated here but is not shipped in the Worker: it is not used at runtime.
const registry = loadRegistry(root);
const problems = validateRegistry(registry);
if (problems.length) throw new Error(`Knowledge base validation failed:\n- ${problems.join('\n- ')}`);

const kb = {};
for (const t of ESSAY_TYPES) {
  kb[t.id] = readFileSync(path.join(root, 'kb', `${t.id}.md`), 'utf8').trim();
}
const sourceById = new Map(registry.sources.map((s) => [s.resource_id, s]));
const rules = Object.fromEntries(ESSAY_TYPES.map((t) => [t.id, []]));
for (const r of registry.rules) {
  const src = sourceById.get(r.resourceId);
  for (const typeId of r.essayTypes) {
    rules[typeId].push({ id: r.id, text: r.text, requiresCurrentCheck: Boolean(r.requiresCurrentCheck), source: { id: src.resource_id, title: src.title, url: src.canonical_url, status: src.verification_status } });
  }
}
writeFileSync(
  path.join(root, 'src/generated/kb.js'),
  `// Generated by scripts/build.mjs from kb/*.md and kb/rules.json. Do not edit; run \`npm run build\`.\nexport const KB = ${JSON.stringify(kb, null, 2)};\nexport const RULES = ${JSON.stringify(rules, null, 2)};\n`,
);

const pkgDir = (name) => path.dirname(require.resolve(`${name}/package.json`));
const vendor = path.join(root, 'public/vendor');
mkdirSync(vendor, { recursive: true });
copyFileSync(path.join(pkgDir('marked'), 'lib/marked.umd.js'), path.join(vendor, 'marked.js'));
copyFileSync(path.join(path.dirname(require.resolve('dompurify')), 'purify.min.js'), path.join(vendor, 'purify.js'));
copyFileSync(path.join(pkgDir('mammoth'), 'mammoth.browser.min.js'), path.join(vendor, 'mammoth.js'));
// Loaded only when a student downloads the PDF report.
copyFileSync(path.join(pkgDir('pdfmake'), 'build/pdfmake.min.js'), path.join(vendor, 'pdfmake.js'));
copyFileSync(path.join(pkgDir('pdfmake'), 'build/vfs_fonts.js'), path.join(vendor, 'pdfmake-fonts.js'));
console.log('built:', Object.keys(prompts).join(', '), '| kb:', Object.keys(kb).length, 'types,', registry.rules.length, 'rules, register', registry.sources.length, 'sources /', registry.assignments.length, 'assignments OK');
