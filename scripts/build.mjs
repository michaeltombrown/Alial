// Generates files that must be committed because the Worker build runs only `wrangler deploy`:
//  - src/generated/prompts.js  from prompts/*.txt  (so Workers can import the prompts)
//  - src/generated/kb.js       from kb/*.md and kb/sources.csv  (essay-type knowledge base)
//  - public/vendor/*           browser libraries copied from node_modules
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, readdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { ESSAY_TYPES } from '../src/essayTypes.js';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const require = createRequire(import.meta.url);

const prompts = {};
for (const file of readdirSync(path.join(root, 'prompts')).filter((f) => f.endsWith('.txt')).sort()) {
  prompts[file.replace(/\.txt$/, '')] = readFileSync(path.join(root, 'prompts', file), 'utf8').trim();
}
mkdirSync(path.join(root, 'src/generated'), { recursive: true });
writeFileSync(
  path.join(root, 'src/generated/prompts.js'),
  `// Generated by scripts/build.mjs from prompts/*.txt. Do not edit; run \`npm run build\`.\nexport const PROMPTS = ${JSON.stringify(prompts, null, 2)};\n`,
);

// ---- knowledge base: one guidance file per essay type, plus the source register (audit sheet)
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some((v) => v.trim())) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field || row.length) { row.push(field); if (row.some((v) => v.trim())) rows.push(row); }
  return rows;
}

const kb = {};
for (const t of ESSAY_TYPES) {
  kb[t.id] = readFileSync(path.join(root, 'kb', `${t.id}.md`), 'utf8').trim();
}
const [header, ...csvRows] = parseCsv(readFileSync(path.join(root, 'kb/sources.csv'), 'utf8').replace(/^\uFEFF/, ''));
const col = (prefix) => header.findIndex((h) => h.trim().startsWith(prefix));
const idx = {
  type: col('Essay Type'), slot: col('Slot'), title: col('Source Title'), url: col('Publisher URL'), score: col('Editorial Score'),
  status: col('Source Status'), use: col('Recommended Use'), checked: col('Official page checked'), reviewed: col('Three-pass'), approved: col('Approved for production'),
};
const sources = Object.fromEntries(ESSAY_TYPES.map((t) => [t.id, []]));
for (const r of csvRows) {
  const type = ESSAY_TYPES.find((t) => t.label === r[idx.type].trim());
  if (!type) throw new Error(`kb/sources.csv: unknown essay type "${r[idx.type]}"`);
  sources[type.id].push({
    slot: Number(r[idx.slot]), title: r[idx.title], url: r[idx.url], score: Number(r[idx.score]), status: r[idx.status], recommendedUse: r[idx.use],
    pageChecked: r[idx.checked].trim().toUpperCase().startsWith('YES'), threePassReviewed: r[idx.reviewed].trim().toUpperCase() === 'YES', approvedForProduction: r[idx.approved].trim().toUpperCase() === 'YES',
  });
}
writeFileSync(
  path.join(root, 'src/generated/kb.js'),
  `// Generated by scripts/build.mjs from kb/*.md and kb/sources.csv. Do not edit; run \`npm run build\`.\nexport const KB = ${JSON.stringify(kb, null, 2)};\nexport const KB_SOURCES = ${JSON.stringify(sources, null, 2)};\n`,
);

const pkgDir = (name) => path.dirname(require.resolve(`${name}/package.json`));
const vendor = path.join(root, 'public/vendor');
mkdirSync(vendor, { recursive: true });
copyFileSync(path.join(pkgDir('marked'), 'lib/marked.umd.js'), path.join(vendor, 'marked.js'));
copyFileSync(path.join(path.dirname(require.resolve('dompurify')), 'purify.min.js'), path.join(vendor, 'purify.js'));
copyFileSync(path.join(pkgDir('mammoth'), 'mammoth.browser.min.js'), path.join(vendor, 'mammoth.js'));
console.log('built:', Object.keys(prompts).join(', '), '| kb:', Object.keys(kb).length, 'types,', csvRows.length, 'sources');
